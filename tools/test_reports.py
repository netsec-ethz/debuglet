"""Coverage ownership and package timing reports from ordinary test evidence."""
import importlib.util
import json
from pathlib import Path
import shutil
import subprocess
import tempfile
import unittest

REPOSITORY = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location('test_report', REPOSITORY / 'tools/test-report.py')
report = importlib.util.module_from_spec(spec)
spec.loader.exec_module(report)


class TestReports(unittest.TestCase):
    def setUp(self):
        temporary = tempfile.TemporaryDirectory()
        self.addCleanup(temporary.cleanup)
        self.root = Path(temporary.name)
        self.output = self.root / '.cache/ci/coverage'
        self.output.mkdir(parents=True)
        (self.root / 'go.mod').write_text('module example.test/demo\n')
        (self.root / 'regular.go').write_text('package demo\n')
        (self.root / 'generated.go').write_text('// Code generated by fixture. DO NOT EDIT.\npackage demo\n')
        (self.output / 'all.out').write_text('mode: set\nexample.test/demo/regular.go:2.1,2.8 2 1\nexample.test/demo/generated.go:3.1,3.8 3 0\n')
        (self.output.parent / 'tests.json').write_text('\n'.join(json.dumps(event) for event in [
            {'Action': 'pass', 'Package': 'example.test/demo', 'Test': 'TestFast', 'Elapsed': 0.1},
            {'Action': 'pass', 'Package': 'example.test/demo', 'Elapsed': 2},
            {'Action': 'fail', 'Package': 'example.test/slow', 'Elapsed': 5},
        ]))

    def test_separates_generated_code_and_sorts_package_times(self):
        report.write_reports(self.root, self.output)
        self.assertEqual((self.output / 'source.out').read_text(), 'mode: set\nexample.test/demo/regular.go:2.1,2.8 2 1\n')
        self.assertEqual((self.output / 'generated.out').read_text(), 'mode: set\nexample.test/demo/generated.go:3.1,3.8 3 0\n')
        self.assertEqual((self.output / 'package-times.csv').read_text().splitlines(), [
            'package,status,elapsed_seconds', 'example.test/slow,fail,5', 'example.test/demo,pass,2'])

    def test_missing_source_cannot_silently_improve_report(self):
        (self.root / 'regular.go').unlink()
        with self.assertRaises(FileNotFoundError):
            report.write_reports(self.root, self.output)

    def test_test_failure_survives_successful_reporting(self):
        (self.root / 'scripts').mkdir()
        (self.root / 'tools').mkdir()
        shutil.copy(REPOSITORY / 'scripts/ci-test.sh', self.root / 'scripts/ci-test.sh')
        shutil.copy(REPOSITORY / 'tools/test-report.py', self.root / 'tools/test-report.py')
        compiler = self.root / 'go-stub'
        compiler.write_text('''#!/bin/sh
if [ "$1" = test ]; then
  printf 'mode: set\\nexample.test/demo/regular.go:2.1,2.8 2 1\\nexample.test/demo/generated.go:3.1,3.8 3 0\\n' > .cache/ci/coverage/all.out
  printf '{"Action":"fail","Package":"example.test/demo","Elapsed":1}\\n'
  exit 7
fi
exit 0
''')
        compiler.chmod(0o755)
        result = subprocess.run(['bash', 'scripts/ci-test.sh', './...'], cwd=self.root,
                                env={'PATH': '/usr/bin:/bin', 'GO': str(compiler)},
                                capture_output=True, text=True, timeout=10)
        self.assertEqual(result.returncode, 7, result.stderr)
        self.assertTrue((self.output / 'source.out').is_file())
